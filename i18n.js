  const NAMES = {
    "zh-CN": "简体中文",
    "zh-TW": "繁體中文",
    en: "English",
    ja: "日本語",
    "pt-BR": "Português",
    es: "Español",
  };

  /** The language for the choice in the settings: "system", or one of LOCALES */
  function pick(choice) {
    return TEXT[choice] ? choice : locale();
  }

  function text(lang = locale()) {
    return TEXT[lang] ?? TEXT.en;
  }

  /** Fills `{name}` in `template` from `vars` */
  function format(template, vars) {
    return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name]));
  }

  globalThis.FocusI18n = { LOCALES, NAMES, locale, pick, text, format };
